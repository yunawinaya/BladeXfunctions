"""Embed the lifted review bodies (lift/review_lift.json -> lib/lift/lift.py) into code/shared/review_chain.js, between its
BEGIN / END LIFTED markers, so the shared chain is ONE file for B2 SUBMIT and A PREPARE (CONTRACT.md section 16).

usage: python3 lift/sync_review_chain.py            (writes lift/lifted_review.js and the region of review_chain.js)
       python3 lift/sync_review_chain.py --check    (exit 1 when either is not what the base bodies give)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SAV2 = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(SAV2, "lib", "lift"))
import lift  # noqa: E402

BEGIN = "// ==== BEGIN LIFTED BODIES (generated by lift/sync_review_chain.py from lift/review_lift.json - do not edit) ===="
END = "// ==== END LIFTED BODIES ===="
CHAIN = os.path.join(SAV2, "code", "shared", "review_chain.js")


def main():
    out, header, sources, rel_root = lift.load_config(os.path.join(HERE, "review_lift.json"))
    text, count = lift.build(sources, header, rel_root)
    chain = open(CHAIN, encoding="utf-8").read()
    a, b = chain.index(BEGIN), chain.index(END)
    new_chain = chain[:a] + BEGIN + "\n" + text + chain[b:]
    if "--check" in sys.argv:
        ok = os.path.exists(out) and open(out, encoding="utf-8").read() == text and new_chain == chain
        print(("IDENTICAL" if ok else "DIFFERS") + f": {os.path.relpath(out, SAV2)} + review_chain.js region ({count} bodies)")
        sys.exit(0 if ok else 1)
    open(out, "w", encoding="utf-8").write(text)
    open(CHAIN, "w", encoding="utf-8").write(new_chain)
    print(f"{os.path.relpath(out, SAV2)} + review_chain.js region: {count} bodies")


if __name__ == "__main__":
    main()
