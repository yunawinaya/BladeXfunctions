def nodes_by_id(path):
    out = {}

    def walk(o):
        if isinstance(o, dict):
            if isinstance(o.get("id"), str) and isinstance(o.get("data"), dict) and "type" in o:
                out[o["id"]] = o
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(json.load(open(path, encoding="utf-8")))
    return out


def body(node):
    code = node["data"]["script"]["code"]
    for m in TOKEN.finditer(code):
        before = code[m.start() - 1] if m.start() else ""
        after = code[m.end()] if m.end() < len(code) else ""
        if before in "'\"`" and after == before:
            raise ValueError(f"{node['id']}: quoted token {m.group(0)}")
    decl = [[r["name"], r.get("bsonType", "any")] for r in node["data"].get("response_json") or []]
    code = TOKEN.sub(lambda m: "__v(" + json.dumps(m.group(1)) + ")", code)
    return (f"  {json.dumps(node['id'])}: {{ decl: {json.dumps(decl)}, fn: function (__v, Date) {{\n"
            f"const console = BN_QUIET;\n{code}\n}} }},\n")


def build():
    nodes = nodes_by_id(SRC)
    parts = [HEAD, RUNTIME, "const BN_BODIES = {\n"]
    for nid in IDS:
        parts.append(f"// GENERATE_BATCH v20 :: {nid} ({nodes[nid]['data'].get('title', '')})\n" + body(nodes[nid]))
    parts.append("};\n")
    parts.append(FLOW)
    return "".join(parts)


def main():
    text = build()
    assert "{{" not in text, "batchnum.js would hold a platform token: the platform substitutes every {{...}} in a code node"

    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print(("IDENTICAL" if same else "DIFFERS") + ": " + OUT)
        sys.exit(0 if same else 1)
    open(OUT, "w", encoding="utf-8").write(text)
    print(OUT, len(text), "chars")


if __name__ == "__main__":
    main()
