"""Lift the classic GR_REVERT_COMPLETED code-node bodies, verbatim, into one JS script that runs them in-process (GR Revert
Completed V2: PREPARE's VPprep / VPplan, SUBMIT's VSgate).

Same contract as scratchpad/pwv2/lift/lift.py: each `{{token}}` becomes `__v("token")` (a fresh deep copy of the value
the platform would substitute, null when it has none); each body becomes
`__N["<id>"] = { decl: [[name, bsonType], ...], fn: function () {...} }` and runs through `__run(id)`
(lift/runtime.js), which applies the platform's output rules and stores the result under `node:<id>`.

Source: Goods Receiving/RevertCompletedGR/GRrevertCompletedWorkflow.json (repo == dev v8): code_node_grRvParams (request
normalisation; V2 feeds it the job's ids), code_node_grRvPrep (header refusals + ledger replay), code_node_grRvBuild
(conflicts + the reversal lists).

usage: python3 lift.py            (writes lift/lifted_prepare.js)
       python3 lift.py --check    (exit 1 when lifted_prepare.js is not what the source gives)
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
TOKEN = re.compile(r"\{\{([^{}]+?)\}\}")
SOURCES = [
    (os.path.join(REPO, "Goods Receiving", "RevertCompletedGR", "GRrevertCompletedWorkflow.json"),
     ["code_node_grRvParams", "code_node_grRvPrep", "code_node_grRvBuild"]),
]
OUT = os.path.join(HERE, "lifted_prepare.js")
# grRvBuild reads V2 answers uncapped (runtime.js __Uncapped: an empty array iterating every row): each may only be read
# from its token, handed to the fetch ceiling and walked with for...of - any other use would see an empty array
UNCAPPED = {
    "batchBalRows": "node:search_node_grRvBatchBal.data.data", "itemBalRows": "node:search_node_grRvItemBal.data.data",
    "onOrderRows": "node:search_node_grRvOnOrder.data.data", "itemRecords": "node:search_node_grRvItems.data.data",
    "transitRows": "node:search_node_grRvTransit.data.data",
}


def check_uncapped(body):
    for var, token in UNCAPPED.items():
        tok = "__v(" + json.dumps(token) + ")"
        if body.count(tok) != 1:
            raise ValueError(f"grRvBuild reads {token} {body.count(tok)} times")
        spans = []
        for pat in (r"const %s = asArr\(%s\);" % (var, re.escape(tok)), r"ceiling\(%s, \d+, " % var, r"for \(const \w+ of %s\)" % var):
            spans += [m.span() for m in re.finditer(pat, body)]
        for m in re.finditer(r"\b%s\b" % var, body):
            if not any(a <= m.start() < b for a, b in spans):
                line = body.count("\n", 0, m.start()) + 1
                raise ValueError(f"grRvBuild uses {var} beyond the ceiling and for...of (body line {line}): the uncapped view cannot serve it")


def nodes_by_id(path):
    out = {}

    def walk(o):
        if isinstance(o, dict):
            if isinstance(o.get("id"), str) and isinstance(o.get("data"), dict) and "type" in o:
                out[o["id"]] = o
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(json.load(open(path, encoding="utf-8")))
    return out


def rewrite(node_id, code):
    for m in TOKEN.finditer(code):
        before = code[m.start() - 1] if m.start() else ""
        after = code[m.end()] if m.end() < len(code) else ""
        if before in "'\"`" and after == before:
            raise ValueError(f"{node_id}: quoted token {m.group(0)}")
    return TOKEN.sub(lambda m: "__v(" + json.dumps(m.group(1)) + ")", code)


def lift(node):
    if node["type"] != "code-node":
        raise ValueError(node["id"] + " is a " + node["type"])
    code = node["data"]["script"]["code"]
    decl = [[r["name"], r.get("bsonType", "any")] for r in node["data"].get("response_json") or []]
    body = rewrite(node["id"], code)
    if node["id"] == "code_node_grRvBuild":
        check_uncapped(body)
    return (
        f"__N[{json.dumps(node['id'])}] = {{ decl: {json.dumps(decl)}, fn: function () {{\n"
        f"const console = __QUIET;\n{body}\n}} }};\n"
    )


def build():
    parts = ["// GENERATED by scratchpad/grrv/lift/lift.py from the deployed workflow JSON (GR_REVERT_COMPLETED dev v8 = repo).\n"
             "// Do not edit: re-run the script.\n"]
    for path, ids in SOURCES:
        nodes = nodes_by_id(path)
        rel = os.path.relpath(path, REPO)
        for nid in ids:
            parts.append(f"// {rel} :: {nid}\n" + lift(nodes[nid]))
    return "".join(parts), sum(len(ids) for _, ids in SOURCES)


def main():
    text, count = build()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print(("IDENTICAL" if same else "DIFFERS") + f": {OUT} ({count} nodes)")
        sys.exit(0 if same else 1)
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"{OUT}: {count} nodes")


if __name__ == "__main__":
    main()
