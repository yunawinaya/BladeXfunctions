"""Lift the classic IA_REVERT v4 code-node bodies VERBATIM into revert/lift/lifted_revert.js (Revert V2 PREPARE / SUBMIT), plus one
declared patch shared with the classic IA_REVERT v6 (PAIR_WAS / PAIR_NOW: RES-01's pairing).

lib/lift/lift.py does the lifting (each {{token}} -> __v("token"), each body -> __N[id] = { decl, fn }); this adds grrv's
uncapped check (tpl/grrv/lift/lift.py check_uncapped): code_node_iaRvBuild gets Item Balance, Item Batch Balance and Item
in full as runtime.js __Uncapped views (an empty array whose for...of yields every row, so its fetch ceiling stays inert);
each such read may only be assigned once, handed to ceiling() and walked with for...of. search_node_iaRvBatch is NOT
uncapped: code_node_iaRvPrep calls .filter on it (CONTRACT.md Revert V2 clarification 5).

usage: python3 revert/lift/lift_revert.py            (writes lifted_revert.js)
       python3 revert/lift/lift_revert.py --check    (exit 1 when lifted_revert.js is not what the base gives)
"""
import json
import os
import re
import sys

sys.dont_write_bytecode = True

HERE = os.path.dirname(os.path.abspath(__file__))
IAV2 = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(IAV2, "lib", "lift"))
import lift as L  # noqa: E402

BASE = os.path.join(IAV2, "base", "IA_REVERT.v4.json")
NODES = ["code_node_iaRvParams", "code_node_iaRvPrep", "code_node_iaRvBuild"]
OUT = os.path.join(HERE, "lifted_revert.js")
# RES-01 (R6 live 10-22): a held component's reversal lands in another bucket (Reserved OUT, Unrestricted / Blocked IN: resRevertAdds),
# so a component pairs without its category; without this a second revert after a re-completion returns the first cycle again
PAIR_WAS = '  S(r.inventory_category) + "|" + S(r.handling_unit_id);'
PAIR_NOW = '  (sideOf(r) === "component" ? "" : S(r.inventory_category)) + "|" + S(r.handling_unit_id);'
HEADER = ("// GENERATED by scratchpad/iav2/revert/lift/lift_revert.py (lib/lift/lift.py) from base/IA_REVERT.v4.json (dev v4 = prod v4).\n"
          "// Do not edit: re-run the script.\n")
UNCAPPED = {
    "itemBalRows": "node:search_node_iaRvItemBal.data.data",
    "batchBalRows": "node:search_node_iaRvBatchBal.data.data",
    "itemRecords": "node:search_node_iaRvItems.data.data",
}


def check_uncapped(body):
    for var, token in UNCAPPED.items():
        tok = "__v(" + json.dumps(token) + ")"
        if body.count(tok) != 1:
            raise ValueError(f"iaRvBuild reads {token} {body.count(tok)} times")
        spans = []
        for pat in (r"const %s = asArr\(%s\);" % (var, re.escape(tok)), r"ceiling\(%s, \d+, " % var, r"for \(const \w+ of %s\)" % var):
            spans += [m.span() for m in re.finditer(pat, body)]
        for m in re.finditer(r"\b%s\b" % var, body):
            if not any(a <= m.start() < b for a, b in spans):
                line = body.count("\n", 0, m.start()) + 1
                raise ValueError(f"iaRvBuild uses {var} beyond the ceiling and for...of (body line {line}): the uncapped view cannot serve it")


def build():
    text, count = L.build([(BASE, NODES)], HEADER, IAV2)
    assert text.count(PAIR_WAS) == 1, "the pairing key moved in the base"
    text = text.replace(PAIR_WAS, PAIR_NOW)
    at = text.index('__N["code_node_iaRvBuild"]')
    check_uncapped(text[at:])
    return text, count


def main():
    text, count = build()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print(("IDENTICAL" if same else "DIFFERS") + f": {os.path.relpath(OUT, IAV2)} ({count} nodes)")
        sys.exit(0 if same else 1)
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"{os.path.relpath(OUT, IAV2)}: {count} nodes")


if __name__ == "__main__":
    main()
