"""Lift deployed code-node bodies, verbatim, into one JS script that runs them in-process.

Each `{{token}}` becomes `__v("token")`: a fresh deep copy of the value the platform would substitute (null when the
token has no value). Each body becomes `__N["<id>"] = { decl: [[name, bsonType], ...], fn: function () {...} }` and is
run through `__run(id)` (lift/runtime.js), which applies the platform's output rules and stores the result under
`node:<id>`.

usage: python3 lift.py <out.js> <workflow.json>:<node_id>,<node_id>,... [<workflow.json>:<ids> ...]
"""
import json
import re
import sys

TOKEN = re.compile(r"\{\{([^{}]+?)\}\}")


def nodes_by_id(path):
    out = {}

    def walk(o):
        if isinstance(o, dict):
            if isinstance(o.get("id"), str) and isinstance(o.get("data"), dict) and "type" in o:
                out[o["id"]] = o
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(json.load(open(path, encoding="utf-8")))
    return out


def rewrite(node_id, code):
    for m in TOKEN.finditer(code):
        before = code[m.start() - 1] if m.start() else ""
        after = code[m.end()] if m.end() < len(code) else ""
        if before in "'\"`" and after == before:
            raise ValueError(f"{node_id}: quoted token {m.group(0)}")
    return TOKEN.sub(lambda m: "__v(" + json.dumps(m.group(1)) + ")", code)


def lift(node):
    if node["type"] != "code-node":
        raise ValueError(node["id"] + " is a " + node["type"])
    code = node["data"]["script"]["code"]
    decl = [[r["name"], r.get("bsonType", "any")] for r in node["data"].get("response_json") or []]
    body = rewrite(node["id"], code)
    return (
        f"__N[{json.dumps(node['id'])}] = {{ decl: {json.dumps(decl)}, fn: function () {{\n"
        f"const console = __QUIET;\n{body}\n}} }};\n"
    )


def main():
    out = sys.argv[1]
    parts = ["// GENERATED by scratchpad/gdc/lift/lift.py from the deployed (repo == dev) workflow JSON. Do not edit.\n"]
    for spec in sys.argv[2:]:
        path, ids = spec.rsplit(":", 1)
        nodes = nodes_by_id(path)
        for nid in ids.split(","):
            parts.append(f"// {path} :: {nid}\n" + lift(nodes[nid]))
    open(out, "w", encoding="utf-8").write("".join(parts))
    print(f"{out}: {len(parts) - 1} nodes")


if __name__ == "__main__":
    main()
