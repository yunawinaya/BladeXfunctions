"""Lift deployed code-node bodies, verbatim, into one JS script that runs them in-process (GR Completion V2 PREPARE).

Same contract as scratchpad/gdc/lift/lift.py: each `{{token}}` becomes `__v("token")` (a fresh deep copy of the value
the platform would substitute, null when it has none); each body becomes
`__N["<id>"] = { decl: [[name, bsonType], ...], fn: function () {...} }` and runs through `__run(id)`
(lift/runtime.js), which applies the platform's output rules and stores the result under `node:<id>`.

usage: python3 lift.py            (writes lift/lifted_prepare.js from the sources below)
       python3 lift.py --check    (exit 1 when lifted_prepare.js is not what the sources give)
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
TOKEN = re.compile(r"\{\{([^{}]+?)\}\}")

# GOODS_RECEIVING (repo == dev v100, == prod v99 minus the Phase 0 guard nodes) in the classic's order, and the one code
# node of CHECK_REQUIRED_FIELD (dev == prod v8) the fill-back's required-field check runs.
SOURCES = [
    (os.path.join(REPO, "Goods Receiving", "GRsaveWorkflow.json"), [
        "code_node_mlTvKeIR", "code_node_4r2Fv9G5", "code_node_wMQADp4i", "code_node_QB3GUnrS", "code_node_Ga3BZDyy",
        "code_node_e9pINRwN", "code_node_origReserved", "code_node_BatchGenPrep", "code_node_NormalizeBatch",
        "code_node_AppendBatch", "code_node_ApplyBatches", "code_node_D9IbUV8t", "code_node_qtCEVR5x", "code_node_H4Eg0oEI",
        "code_node_W4nXz7Yb", "code_node_ip8w2l8k", "code_node_hRG2RgIm", "code_node_ngFX3hcL", "code_node_7kcbaray",
        "code_node_ITrow", "code_node_KAeXsqwm", "code_node_pdqxs8pN", "code_node_UQWzCg37", "code_node_jo9g6Ldx",
        "code_node_ITrows", "code_node_2Cq2eMRb",
    ]),
    (os.path.join(HERE, "src", "CHECK_REQUIRED_FIELD.v8.json"), ["code_node_AeSdXE85"]),
]
OUT = os.path.join(HERE, "lifted_prepare.js")


def nodes_by_id(path):
    out = {}

    def walk(o):
        if isinstance(o, dict):
            if isinstance(o.get("id"), str) and isinstance(o.get("data"), dict) and "type" in o:
                out[o["id"]] = o
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(json.load(open(path, encoding="utf-8")))
    return out


def rewrite(node_id, code):
    for m in TOKEN.finditer(code):
        before = code[m.start() - 1] if m.start() else ""
        after = code[m.end()] if m.end() < len(code) else ""
        if before in "'\"`" and after == before:
            raise ValueError(f"{node_id}: quoted token {m.group(0)}")
    return TOKEN.sub(lambda m: "__v(" + json.dumps(m.group(1)) + ")", code)


def lift(node):
    if node["type"] != "code-node":
        raise ValueError(node["id"] + " is a " + node["type"])
    code = node["data"]["script"]["code"]
    decl = [[r["name"], r.get("bsonType", "any")] for r in node["data"].get("response_json") or []]
    body = rewrite(node["id"], code)
    return (
        f"__N[{json.dumps(node['id'])}] = {{ decl: {json.dumps(decl)}, fn: function () {{\n"
        f"const console = __QUIET;\n{body}\n}} }};\n"
    )


def build():
    parts = ["// GENERATED by scratchpad/grv2/lift/lift.py from the deployed workflow JSON (GOODS_RECEIVING dev v100 = repo,\n"
             "// CHECK_REQUIRED_FIELD v8). Do not edit: re-run the script.\n"]
    for path, ids in SOURCES:
        nodes = nodes_by_id(path)
        rel = os.path.relpath(path, REPO)
        for nid in ids:
            parts.append(f"// {rel} :: {nid}\n" + lift(nodes[nid]))
    return "".join(parts), sum(len(ids) for _, ids in SOURCES)


def main():
    text, count = build()
    assert "{{" not in text, "a lifted body still holds a platform token"

    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print(("IDENTICAL" if same else "DIFFERS") + f": {OUT} ({count} nodes)")
        sys.exit(0 if same else 1)
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"{OUT}: {count} nodes")


if __name__ == "__main__":
    main()
