SELECT DATE_FORMAT(n.t, '%Y-%m-%d %H:%i:%s') AS db_now,
       DATE_FORMAT(n.t + INTERVAL 30 MINUTE, '%Y-%m-%d %H:%i:%s') AS lease_until,
       CAST(j.id AS CHAR) AS id,
       j.organization_id,
       j.plant_id,
       j.command,
       j.payload_hash,
       j.correlation_id,
       j.job_status,
       j.progress_percent,
       j.attempt_count,
       DATE_FORMAT(j.next_attempt_at, '%Y-%m-%d %H:%i:%s') AS next_attempt_at,
       j.lease_owner,
       DATE_FORMAT(j.lease_expires_at, '%Y-%m-%d %H:%i:%s') AS lease_expires_at,
       (j.lease_expires_at > n.t) AS lease_live,
       j.cancel_requested,
       j.row_version,
       j.error_code,
       j.error_message,
       j.error_details,
       j.line_count,
       CAST(j.gd_id AS CHAR) AS gd_id,
       j.gd_no,
       DATE_FORMAT(j.started_at, '%Y-%m-%d %H:%i:%s') AS started_at,
       (j.next_attempt_at IS NULL OR j.next_attempt_at <= n.t) AS due,
       j.is_deleted
  FROM (SELECT NOW(3) AS t) n
  LEFT JOIN gd_async_job j
    ON j.tenant_id = '{{node:code_node_WaEyJtlE.data.tenantId}}'
   AND j.id = {{node:code_node_WaEyJtlE.data.jobId}}