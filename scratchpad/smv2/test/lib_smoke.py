"""Smoke test of scratchpad/smv2/lib: every copy loads and behaves like its source.

  1. v2build.build_worker(gr_worker_config())  == build_grv2.build_worker()     (fresh processes: same wfkit key stream)
     ... with the worker JS from code/worker_src_grv2 (the copy)              == the same
     v2build.build_worker(pw_worker_config())  == build_pwv2.build_worker()
     both also after wrap_doc_sql, and GR's against the deployed Goods Receiving/CompleteV2/GR_COMPLETE_WORKER.json
     (response_json keys are random per build: compared with the keys blanked)
  2. lib/lift/lift.py on Putaway V2's sources == scratchpad/pwv2/lift/lift.py build()
  3. lift + runtime.js run two lifted v82 bodies in node (base/SM_LOCATION_TRANSFER.v82.json)
  4. dbq / fmt / outline / sqlcheck / test_load.js / sim (test_flow.js output == the original's)

usage: python3 test/lib_smoke.py [--no-db]    (--no-db skips the dev SELECTs: dbq and sqlcheck)
Read-only: writes nothing outside the session temp dir.
"""
import importlib.util
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SMV2 = os.path.dirname(HERE)
LIB = os.path.join(SMV2, "lib")
SCRATCH = os.path.dirname(SMV2)
REPO = os.path.dirname(SCRATCH)
NO_DB = "--no-db" in sys.argv
fails = []


def check(label, ok, extra=""):
    print(("ok   " if ok else "FAIL ") + label + ("" if ok or not extra else "  " + str(extra)[:500]))
    if not ok:
        fails.append(label)


def py(code, path):
    r = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, cwd=path)
    if r.returncode:
        raise RuntimeError(r.stderr[-1500:])
    return r.stdout


def blank_keys(o):
    if isinstance(o, dict):
        return {k: ("" if k == "key" else blank_keys(v)) for k, v in o.items()}
    if isinstance(o, list):
        return [blank_keys(v) for v in o]
    return o


# ------------------------------------------------------------------------------------------- 1. worker identity
DUMP = "import json, sys; sys.stdout.write(json.dumps({'raw': doc, 'wrapped': W(json.loads(json.dumps(doc)))}, ensure_ascii=False))"
gr_old = json.loads(py("import sys; sys.path.insert(0, %r); import build_grv2 as G; doc = G.build_worker(); W = G.wrap_doc_sql; %s" % (
    os.path.join(SCRATCH, "grv2"), DUMP), os.path.join(SCRATCH, "grv2")))
gr_new = json.loads(py("import sys; sys.path.insert(0, %r); import v2build as V; doc = V.build_worker(V.gr_worker_config()); W = V.wrap_doc_sql; %s" % (LIB, DUMP), LIB))
gr_copy = json.loads(py("import sys; sys.path.insert(0, %r); import v2build as V; doc = V.build_worker(V.gr_worker_config(code_dir=%r)); W = V.wrap_doc_sql; %s" % (
    LIB, os.path.join(SMV2, "code", "worker_src_grv2"), DUMP), LIB))
check("GR worker: v2build == build_grv2.build_worker (raw JSON)", gr_old["raw"] == gr_new["raw"])
check("GR worker: v2build == build_grv2.build_worker (after wrap_doc_sql)", gr_old["wrapped"] == gr_new["wrapped"])
check("GR worker: v2build on code/worker_src_grv2 == build_grv2.build_worker", gr_old["raw"] == gr_copy["raw"])
deployed = json.load(open(os.path.join(REPO, "Goods Receiving", "CompleteV2", "GR_COMPLETE_WORKER.json"), encoding="utf-8"))
check("GR worker: v2build == repo GR_COMPLETE_WORKER.json (keys blanked)", blank_keys(deployed) == blank_keys(gr_new["wrapped"]))
pw_old = json.loads(py("import sys; sys.path.insert(0, %r); import build_pwv2 as P; doc = P.build_worker(); W = P.G.wrap_doc_sql; %s" % (
    os.path.join(SCRATCH, "pwv2"), DUMP), os.path.join(SCRATCH, "pwv2")))
pw_new = json.loads(py("import sys; sys.path.insert(0, %r); import v2build as V; doc = V.build_worker(V.pw_worker_config()); W = V.wrap_doc_sql; %s" % (LIB, DUMP), LIB))
check("PW worker: v2build == build_pwv2.build_worker (raw JSON)", pw_old["raw"] == pw_new["raw"])
check("PW worker: v2build == build_pwv2.build_worker (after wrap_doc_sql)", pw_old["wrapped"] == pw_new["wrapped"])
pw_dep = json.load(open(os.path.join(REPO, "Putaway", "AsyncV2", "PUTAWAY_ASYNC_WORKER.json"), encoding="utf-8"))
same_pw = blank_keys(pw_dep) == blank_keys(pw_new["wrapped"])
print(("ok   " if same_pw else "note ") + "PW worker: v2build == repo PUTAWAY_ASYNC_WORKER.json (keys blanked)" + ("" if same_pw else " - differs (informational: the repo file may be ahead of build_pwv2)"))

# ------------------------------------------------------------------------------------------- 2. lift identity
spec = importlib.util.spec_from_file_location("pw_lift", os.path.join(SCRATCH, "pwv2", "lift", "lift.py"))
pw_lift = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pw_lift)
old_text, old_n = pw_lift.build()
spec2 = importlib.util.spec_from_file_location("smv2_lift", os.path.join(LIB, "lift", "lift.py"))
lift = importlib.util.module_from_spec(spec2)
spec2.loader.exec_module(lift)
header = ("// GENERATED by scratchpad/pwv2/lift/lift.py from the deployed workflow JSON (PUTAWAY_LOOP dev v16 = repo,\n"
          "// PUTAWAY dev v34 = repo, CHECK_REQUIRED_FIELD v8). Do not edit: re-run the script.\n")
new_text, new_n = lift.build(pw_lift.SOURCES, header, REPO)
check("lift: lib/lift/lift.py == pwv2/lift/lift.py on the Putaway sources (%d bodies)" % new_n, old_text == new_text and old_n == new_n)

# ------------------------------------------------------------------------------------------- 3. lift + runtime on v82
V82 = os.path.join(SMV2, "base", "SM_LOCATION_TRANSFER.v82.json")
text, n = lift.build([(V82, ["code_node_LOTmainDocId", "code_node_kuH3MokM"])], "// smoke\n", SMV2)
tmp = tempfile.mkdtemp(prefix="smv2_smoke_")
js = os.path.join(tmp, "lifted.js")
runtime = open(os.path.join(LIB, "lift", "runtime.js"), encoding="utf-8").read()
open(js, "w", encoding="utf-8").write(runtime + "\n" + text + """
__set("workflowparams:pageStatus", "Edit");
__set("node:code_node_yPlLXIZW", { data: { allData: { id: "2105231525751984129", stock_movement_no: "LOT-1", movement_type: "Location Transfer", issue_date: "2026-10-16 00:00:00",
  issuing_operation_faci: "1", stock_movement: [{ id: "1" }] } } });
const a = __run("code_node_LOTmainDocId");
const b = __run("code_node_kuH3MokM");
process.stdout.write(JSON.stringify({ a: a, fields: JSON.parse(b.required_fields).length, data: JSON.parse(b.data).stock_movement_no }));
""")
r = subprocess.run(["node", js], capture_output=True, text=True)
out = json.loads(r.stdout) if r.returncode == 0 else {"err": r.stderr[-800:]}
check("lift + runtime: lifted v82 LOTmainDocId / kuH3MokM run in node", out == {"a": {"docId": "2105231525751984129"}, "fields": 5, "data": "LOT-1"}, out)

# ------------------------------------------------------------------------------------------- 4. the small tools
sys.path.insert(0, LIB)
import fmt  # noqa: E402
import outline  # noqa: E402
check("fmt.render (Prettier json)", fmt.render({"a": [1, 2]}) == '{ "a": [1, 2] }\n', fmt.render({"a": [1, 2]}))
lines = []
outline.walk(json.load(open(V82, encoding="utf-8"))["nodes"], 0, lines)
check("outline.walk on v82 (219 nodes)", len(lines) == 219, len(lines))
if not NO_DB:
    from dbq import q  # noqa: E402
    rows = q("--dev", "SELECT 1 AS one, CAST(2109916822821744641 AS CHAR) AS id")
    check("dbq.q on dev", rows == [{"one": 1, "id": "2109916822821744641"}], rows)
    import sqlcheck  # noqa: E402
    sd = os.path.join(tmp, "wf")
    os.makedirs(sd)
    json.dump(deployed, open(os.path.join(sd, "GR_COMPLETE_WORKER.json"), "w"))
    report = []
    bad = sqlcheck.run(sd, {"*": {"tenantId": "000000", "jobId": "2110228531056345089", "jobIdsSql": "2110228531056345089"}}, printer=report.append)
    check("sqlcheck.run on the deployed GR_COMPLETE_WORKER (%d sql nodes, read-only dev)" % (len(report) - 1), bad == 0, report)
r = subprocess.run(["node", "-e", "const load = require(%r); const m = load('c2.js', ['commitC2', 'stepEnd', 'sameVal'], []); "
                    "process.stdout.write([typeof m.commitC2, typeof m.stepEnd, m.sameVal('1.50000000', 1.5)].join(','))" % os.path.join(LIB, "test_load.js")],
                   capture_output=True, text=True, env=dict(os.environ, V2_CODE_DIR=os.path.join(SCRATCH, "grv2", "code")))
check("test_load.js loads a GR COMMIT step (V2_CODE_DIR = grv2/code)", r.stdout == "function,function,true", r.stdout + r.stderr[-400:])
# the interpreter on a v2build output: the GR worker with no due job answers IDLE (code / sql / cache / loop / return nodes)
wd = os.path.join(tmp, "sim")
os.makedirs(wd)
json.dump(gr_new["wrapped"], open(os.path.join(wd, "GR_COMPLETE_WORKER.json"), "w"))
r = subprocess.run(["node", "-e", """
const { Engine } = require(%r);
const db = { tenantId: "000000", insert: () => [], update: () => [] };
const mocks = { sql: { sql_node_RWpoll: () => [{ db_now: "2026-10-16 08:00:00", id: null }], sql_node_RWfinal: () => [] }, read: {} };
const e = new Engine({ dir: %r, db: db, mocks: mocks });
const r = e.run("GR_COMPLETE_WORKER", { job_id: "" }).returned;
process.stdout.write(JSON.stringify([r.worker_route, r.processed, r.jobs]));
""" % (os.path.join(LIB, "sim", "engine.js"), wd)], capture_output=True, text=True)
check("sim: lib/sim/engine.js runs a v2build worker (no due job -> IDLE)", r.stdout == '["IDLE","0","[]"]', r.stdout + r.stderr[-600:])
# test_flow.js is the Picking V2 example of the original; its db.js mocks predate today's Picking JSON (both stop at
# "no SQL mock for sql_node_PSmove"), so only "the copy behaves as the original" is checked
a = subprocess.run(["node", os.path.join(SCRATCH, "gdc", "pkv2tools", "sim", "test_flow.js")], capture_output=True, text=True)
b = subprocess.run(["node", os.path.join(LIB, "sim", "test_flow.js")], capture_output=True, text=True)
first_err = lambda t: next((l for l in t.splitlines() if l.startswith("Error")), "")
check("sim: lib/sim/test_flow.js behaves as gdc/pkv2tools/sim/test_flow.js (exit %d, %s)" % (a.returncode, first_err(a.stderr) or "passed"),
      a.stdout == b.stdout and a.returncode == b.returncode and first_err(a.stderr) == first_err(b.stderr), (a.stdout[-300:], b.stdout[-300:], b.stderr[-300:]))

print("ALL PASSED" if not fails else "%d FAILED: %s" % (len(fails), fails))
sys.exit(1 if fails else 0)
