"""Lift deployed code-node bodies, verbatim, into one JS script that runs them in-process (V2 PREPARE / SUBMIT gates).

Copy of scratchpad/pwv2/lift/lift.py (same contract as scratchpad/grv2/lift/lift.py): each `{{token}}` becomes
`__v("token")` (a fresh deep copy of the value the platform would substitute, null when it has none); each body becomes
`__N["<id>"] = { decl: [[name, bsonType], ...], fn: function () {...} }` and runs through `__run(id)` (lift/runtime.js),
which applies the platform's output rules and stores the result under `node:<id>`.

Changed from the pwv2 copy: the SOURCES / OUT / header are a config (a JSON file, or build() arguments) instead of module
constants, and the "{{" left-over assertion of the grv2 copy is back. The lifting itself (nodes_by_id, rewrite, lift) is
unchanged.

usage: python3 lift.py <config.json>            (writes the config's "out")
       python3 lift.py <config.json> --check    (exit 1 when "out" is not what the sources give)
config: { "out": "<file>", "header": "<comment text, one or more // lines>",
          "sources": [["<workflow JSON>", ["code_node_x", ...]], ...] }   (relative paths: against the config's folder)
"""
import json
import os
import re
import sys

TOKEN = re.compile(r"\{\{([^{}]+?)\}\}")


def nodes_by_id(path):
    out = {}

    def walk(o):
        if isinstance(o, dict):
            if isinstance(o.get("id"), str) and isinstance(o.get("data"), dict) and "type" in o:
                out[o["id"]] = o
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(json.load(open(path, encoding="utf-8")))
    return out


def rewrite(node_id, code):
    for m in TOKEN.finditer(code):
        before = code[m.start() - 1] if m.start() else ""
        after = code[m.end()] if m.end() < len(code) else ""
        if before in "'\"`" and after == before:
            raise ValueError(f"{node_id}: quoted token {m.group(0)}")
    return TOKEN.sub(lambda m: "__v(" + json.dumps(m.group(1)) + ")", code)


def lift(node):
    if node["type"] != "code-node":
        raise ValueError(node["id"] + " is a " + node["type"])
    code = node["data"]["script"]["code"]
    decl = [[r["name"], r.get("bsonType", "any")] for r in node["data"].get("response_json") or []]
    body = rewrite(node["id"], code)
    return (
        f"__N[{json.dumps(node['id'])}] = {{ decl: {json.dumps(decl)}, fn: function () {{\n"
        f"const console = __QUIET;\n{body}\n}} }};\n"
    )


def build(sources, header, rel_root):
    """sources: [(workflow JSON path, [node ids])]; the comment line before each body names the path relative to rel_root"""
    parts = [header]
    for path, ids in sources:
        nodes = nodes_by_id(path)
        rel = os.path.relpath(path, rel_root)
        for nid in ids:
            if nid not in nodes:
                raise KeyError(f"{nid} is not in {rel}")
            parts.append(f"// {rel} :: {nid}\n" + lift(nodes[nid]))
    text = "".join(parts)
    assert "{{" not in text, "a lifted body still holds a platform token"
    return text, sum(len(ids) for _, ids in sources)


def load_config(path):
    cfg = json.load(open(path, encoding="utf-8"))
    base = os.path.dirname(os.path.abspath(path))
    at = lambda p: p if os.path.isabs(p) else os.path.normpath(os.path.join(base, p))
    header = cfg.get("header") or "// GENERATED by scratchpad/smv2/lib/lift/lift.py. Do not edit: re-run the script.\n"
    if not header.endswith("\n"):
        header += "\n"
    return at(cfg["out"]), header, [(at(p), list(ids)) for p, ids in cfg["sources"]], at(cfg.get("rel_root", "."))


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        sys.exit(__doc__)
    out, header, sources, rel_root = load_config(args[0])
    text, count = build(sources, header, rel_root)
    if "--check" in sys.argv:
        same = os.path.exists(out) and open(out, encoding="utf-8").read() == text
        print(("IDENTICAL" if same else "DIFFERS") + f": {out} ({count} nodes)")
        sys.exit(0 if same else 1)
    open(out, "w", encoding="utf-8").write(text)
    print(f"{out}: {count} nodes")


if __name__ == "__main__":
    main()
